#!/usr/bin/env python3
"""Packs the DINOBYTE sheet (assets/dinobyte/dbyte_1x.png: 16x16 cells of 6x8, code page 437) into
font_data.odin, one u64 per glyph, bit (row * 6 + col) set when the pixel is inked.
Usage: python3 odin/tools/gen_font.py   (run from anywhere)"""
import os
from PIL import Image

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sheet = Image.open(os.path.join(root, "assets/dinobyte/dbyte_1x.png")).convert("RGBA")
assert sheet.size == (96, 128), sheet.size
rows = []
for code in range(256):
    cx, cy = (code % 16) * 6, (code // 16) * 8
    bits = 0
    for y in range(8):
        for x in range(6):
            if sheet.getpixel((cx + x, cy + y))[3] > 0:
                bits |= 1 << (y * 6 + x)
    rows.append(bits)
lines = [
    "package sbos",
    "",
    "// 6x8 glyph bitmaps, one u64 per character (code page 437). Bit (row*6 + col) is set when that pixel is lit.",
    "// DINOBYTE bitmap font by mby, https://mby.itch.io/dinobyte, CC BY 4.0. Generated by tools/gen_font.py from",
    "// assets/dinobyte/dbyte_1x.png, unmodified. Credit it wherever the game is shipped (see assets/dinobyte/NOTICE.txt).",
    "",
    "GLYPHS := [256]u64{",
]
for i in range(0, 256, 4):
    lines.append("\t" + " ".join("0x%012X," % v for v in rows[i:i + 4]))
lines.append("}")
open(os.path.join(root, "font_data.odin"), "w").write("\n".join(lines) + "\n")
